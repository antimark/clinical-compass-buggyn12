'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),files=path.join(root,'frontend/dist/assets/js');
const js=(file)=>fs.readFileSync(path.join(files,file),'utf8');
const escape=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
let sideEffects=[],ctx={window:{CC:{escape},CCAPI:{isMock:false}},URL:{revokeObjectURL:s=>sideEffects.push('revoke:'+s),createObjectURL:()=>{sideEffects.push('preview');return 'blob:synthetic';}},document:{},location:{},console,FormData:class {constructor(form){this.form=form}*[Symbol.iterator](){yield*Object.entries(this.form.values||{})}},Object,Array,Number,String,Date,RegExp,Error};
vm.createContext(ctx);vm.runInContext(js('demo_completion_v1.js'),ctx);
const obj=ctx.window.CCDemoCompletion;
const me=(role,enabled=true)=>({context:{role},features:{synthetic_onboarding_enabled:enabled},user:{id:'demo_'+role,display_name:'Синтетический пользователь'}});
assert.equal(obj.enabled(me('doctor',false)),false);
assert.ok(obj.render('/demo/journeys',me('doctor',false)).includes('Нет доступа'));
assert.ok(obj.render('/demo/journeys',me('patient')).includes('D10'));
assert.ok(obj.render('/demo/profile',me('doctor')).includes('Редактор')===false || obj.render('/demo/profile',me('doctor')).includes('Образование'));
let markup=obj.render('/demo/profile',me('doctor'));
for(const s of ['Бакалавриат','Магистратура','Специалитет','Ординатура','Аспирантура','Докторантура','Дополнительное образование','Публикации','UI_MOCK','Нет серверного сохранения'])assert.ok(markup.includes(s),'missing '+s);
assert.ok(markup.includes('type="file"'));
const form=(name,values)=>({dataset:{form:name},values});
obj.submit(form('dc-edit-education',{id:'',type:'residency',institution:'Учебный университет',specialization:'Психиатрия',year_from:'2018',year_to:'2020',status:'completed'}));
markup=obj.render('/demo/profile',me('doctor'));assert.ok(markup.includes('Учебный университет'));
const marker=/data-kind="education" data-id="([^"]+)"/.exec(markup);assert.ok(marker);
const outcome=obj.action({dataset:{action:'dc-remove',kind:'education',id:marker[1]}});
assert.equal(outcome.rerender,true);
assert.ok(!obj.render('/demo/profile',me('doctor')).includes('Учебный университет'));
assert.throws(()=>obj.submit(form('dc-edit-education',{year_from:'2025',year_to:'2024'})),/годы/);
assert.throws(()=>obj.submit(form('dc-edit-publication',{title:'X',journal:'Y',published_at:'2026-15',doi:''})),/дату/);
obj.submit(form('dc-edit-publication',{title:'Проверка',journal:'Учебный',published_at:'2026-05',doi:''}));
assert.ok(obj.render('/demo/profile',me('doctor')).includes('Проверка'));
assert.throws(()=>obj.photo({type:'image/svg+xml',size:1024}),/Только JPEG/);
assert.throws(()=>obj.photo({type:'image/png',size:4*1024*1024}),/до 2 МБ/);
obj.photo({type:'image/png',size:2048});assert.ok(sideEffects.includes('preview'));
assert.ok(obj.render('/demo/profile',me('doctor')).includes('blob:synthetic'));
assert.ok(obj.render('/demo/profile',me('patient')).includes('дневники не входят'));
assert.throws(()=>obj.submit(form('dc-edit-education',{year_from:'2018',year_to:'2020'})),/врачу|специалиста/);
assert.equal(obj.enabled({features:{synthetic_onboarding_enabled:true},context:{role:'patient'}}),true);
assert.ok(!/localStorage|sessionStorage|\.post\(/.test(js('demo_completion_v1.js')),'no browser persistence or fake post');
const html=fs.readFileSync(path.join(root,'frontend/dist/index.html'),'utf8');
assert.ok(html.includes('/assets/js/demo_completion_v1.js'));
assert.ok(html.indexOf('demo_completion_v1.js')<html.indexOf('live_app.js'));
console.log('PASS: demo UI gating, roles, repeaters, year checks, publication, photo, no fake persistence, integration');
